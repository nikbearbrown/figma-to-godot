"""figma2godot build design.json --project path/to/godot_project"""
import argparse
import json
import os
import sys

from .tokens import Tokens, build_theme, mode_file
from .scene import Converter, Report
from .util import slug

SCHEMA = "figma-to-godot/0.1"

THEME_HELPER = '''# Generated by figma2godot. Swap every Figma variable mode at runtime:
#   FigmaTheme.apply($MainMenu, "Light")
extends RefCounted
class_name FigmaTheme

const MODES := {
%s
}

static func apply(root: Control, mode: String) -> void:
	var key := mode.to_lower()
	if not MODES.has(key):
		push_error("FigmaTheme: unknown mode '%%s' (have %%s)" %% [mode, MODES.keys()])
		return
	root.theme = load(MODES[key])
'''


def load_design(path):
    with open(path) as f:
        d = json.load(f)
    if d.get("schema") != SCHEMA:
        raise SystemExit("%s: expected schema %r, got %r" % (path, SCHEMA, d.get("schema")))
    return d


def build(design, project, subdir="figma"):
    report = Report()
    tokens = Tokens(design, report)
    res_root = "res://%s" % subdir
    theme_dir = os.path.join(project, subdir, "theme")
    scene_dir = os.path.join(project, subdir, "scenes")
    os.makedirs(theme_dir, exist_ok=True)
    os.makedirs(scene_dir, exist_ok=True)

    conv = Converter(
        tokens, report,
        "%s/theme/%s" % (res_root, mode_file(tokens.default_mode)),
        "%s/assets" % res_root, os.path.join(project, subdir, "assets"))

    written = []
    for frame in design.get("frames", []):
        text = conv.convert_frame(frame)
        path = os.path.join(scene_dir, "%s.tscn" % slug(frame["name"]))
        with open(path, "w") as f:
            f.write(text)
        written.append(path)

    for mode in tokens.modes:
        path = os.path.join(theme_dir, mode_file(mode))
        with open(path, "w") as f:
            f.write(build_theme(tokens, mode, conv.variations))
        written.append(path)

    modes = ",\n".join('\t"%s": "%s/theme/%s"' % (m.lower(), res_root, mode_file(m))
                       for m in tokens.modes)
    helper = os.path.join(theme_dir, "figma_theme.gd")
    with open(helper, "w") as f:
        f.write(THEME_HELPER % modes)
    written.append(helper)

    rpt = os.path.join(project, subdir, "figma_import_report.md")
    with open(rpt, "w") as f:
        f.write(report.markdown(design.get("file", "design")))
    written.append(rpt)
    return written, report


def main(argv=None):
    ap = argparse.ArgumentParser(prog="figma2godot")
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build", help="convert a design JSON into Godot scenes + themes")
    b.add_argument("design")
    b.add_argument("--project", required=True, help="Godot project folder (has project.godot)")
    b.add_argument("--subdir", default="figma", help="folder inside the project (default: figma)")
    args = ap.parse_args(argv)
    design = load_design(args.design)
    written, report = build(design, args.project, args.subdir)
    for w in written:
        print(w)
    print("%d report item(s): see %s/figma_import_report.md" % (len(report.items), args.subdir))
    return 0


if __name__ == "__main__":
    sys.exit(main())
