SCREEN_GD = '''# Generated by figma2godot. Do not edit: change the Figma file and convert again.
extends Control
## The root of a screen that came from Figma.
##
## It gives the game one place to listen. Connect to `action` for presses and to
## `value_changed` for toggles, sliders, dropdowns and text fields. The ids are the
## [action=...] tags from the Figma layer names (see HANDOFF.md).

signal action(id: StringName, source: Control)
signal value_changed(id: StringName, value: Variant, source: Control)

## The control that has focus when the screen opens. Without one, a controller does nothing.
@export var initial_focus: NodePath
@export var platform: StringName = &"pc"
@export var design_size := Vector2(1920, 1080)

func _ready() -> void:
	for c in tagged_controls():
		_wire(c)
	focus_first()

## Call again when the screen is shown after being hidden.
func focus_first() -> void:
	if initial_focus.is_empty():
		return
	var n := get_node_or_null(initial_focus) as Control
	if n == null:
		push_error("FigmaScreen %s: initial_focus %s is not a Control" % [name, initial_focus])
		return
	n.grab_focus.call_deferred()

## Every control that carries an action id, in tree order.
func tagged_controls() -> Array[Control]:
	var out: Array[Control] = []
	_collect(self, out)
	return out

## The controls for one action id (usually one).
func controls_for(id: StringName) -> Array[Control]:
	var out: Array[Control] = []
	for c in tagged_controls():
		if c.get_meta(&"figma_action") == id:
			out.append(c)
	return out

func _collect(n: Node, out: Array[Control]) -> void:
	for ch in n.get_children():
		if ch is Control and ch.has_meta(&"figma_action"):
			out.append(ch)
		_collect(ch, out)

func _wire(c: Control) -> void:
	var id: StringName = c.get_meta(&"figma_action")
	if c is OptionButton:
		(c as OptionButton).item_selected.connect(func(i: int) -> void: value_changed.emit(id, i, c))
	elif c is BaseButton and (c as BaseButton).toggle_mode:
		(c as BaseButton).toggled.connect(func(on: bool) -> void: value_changed.emit(id, on, c))
	elif c is BaseButton:
		(c as BaseButton).pressed.connect(func() -> void: action.emit(id, c))
	elif c is Range:
		(c as Range).value_changed.connect(func(v: float) -> void: value_changed.emit(id, v, c))
	elif c is LineEdit:
		(c as LineEdit).text_submitted.connect(func(t: String) -> void: value_changed.emit(id, t, c))
'''

SAFE_GD = '''# Generated by figma2godot. Do not edit: change the Figma file and convert again.
extends MarginContainer
## Keeps a screen's content inside the safe area, and never inside the design's own padding.
##
## "title": the inner part of a TV picture (televisions still overscan).
## "device": what the phone reports at run time (notches, rounded corners, home indicator).

@export_enum("title", "device") var mode := "title"
## Share of the screen kept clear on every side in "title" mode.
@export_range(0.0, 0.1) var inset := 0.05
## The padding the Figma frame had: left, top, right, bottom. The larger of this and the safe inset wins.
@export var design_margins := Vector4i.ZERO

func _ready() -> void:
	get_viewport().size_changed.connect(_apply)
	_apply()

func _apply() -> void:
	var view := get_viewport().get_visible_rect().size
	var l := 0.0
	var t := 0.0
	var r := 0.0
	var b := 0.0
	if mode == "title":
		l = view.x * inset
		r = l
		t = view.y * inset
		b = t
	else:
		var safe := DisplayServer.get_display_safe_area()
		var win := Rect2i(DisplayServer.window_get_position(), DisplayServer.window_get_size())
		if safe.size.x > 0 and safe.size.y > 0 and win.size.x > 0 and win.size.y > 0:
			var sx := view.x / float(win.size.x)
			var sy := view.y / float(win.size.y)
			l = maxf(0.0, safe.position.x - win.position.x) * sx
			t = maxf(0.0, safe.position.y - win.position.y) * sy
			r = maxf(0.0, win.end.x - safe.end.x) * sx
			b = maxf(0.0, win.end.y - safe.end.y) * sy
	add_theme_constant_override(&"margin_left", maxi(design_margins.x, int(ceil(l))))
	add_theme_constant_override(&"margin_top", maxi(design_margins.y, int(ceil(t))))
	add_theme_constant_override(&"margin_right", maxi(design_margins.z, int(ceil(r))))
	add_theme_constant_override(&"margin_bottom", maxi(design_margins.w, int(ceil(b))))
'''

INPUT_MODE_GD = '''# Generated by figma2godot. Do not edit: change the Figma file and convert again.
extends Node
## Tells the game which device the player is using, so button prompts can follow it.
## Register it as an autoload named InputMode, then listen to `changed` and swap the
## texture or text of every node that has the meta "figma_prompt".

signal changed(mode: StringName)

var mode: StringName = &"kbm"

func _input(event: InputEvent) -> void:
	var next := mode
	if event is InputEventJoypadButton:
		next = &"pad"
	elif event is InputEventJoypadMotion and absf((event as InputEventJoypadMotion).axis_value) > 0.5:
		next = &"pad"  # the 0.5 keeps stick drift from flipping the prompts back and forth
	elif event is InputEventScreenTouch:
		next = &"touch"
	elif event is InputEventKey or event is InputEventMouseButton:
		next = &"kbm"
	if next != mode:
		mode = next
		changed.emit(mode)
'''

# Walker's Godot rules (bear-textbooks/books/walker: engines/godot.md and the asset-organization
# report), cut down to what applies to wiring UI scenes that this tool generated.
IMPLEMENTER_RULES = [
    ("Do not edit anything under this folder.",
     "Scenes, themes and scripts here are generated and will be overwritten. To change how a screen looks, change the Figma file (a layer name, a tag, a variable) and convert again. To change what it does, write code outside this folder."),
    ("Listen to the screen, not to its buttons.",
     "Each screen's root has two signals: `action(id, source)` and `value_changed(id, value, source)`. Connect to those. Do not reach into the generated node tree by path: paths change when the design changes; action ids do not."),
    ("If you must reach a control, use its unique name.",
     "Tagged controls have `unique_name_in_owner` set, so `%PlayButton` (GDScript) or `GetNode<Button>(\"%PlayButton\")` (C#) keeps working when the layout moves."),
    ("Put game code where the game keeps it.",
     "A screen's behavior lives beside the feature it belongs to (for example `ui/menus/main_menu.gd`), not in this folder. Files and folders are snake_case; a scene's root node is PascalCase. Keep generation inputs and references outside the Godot project."),
    ("Use the project's language.",
     "The generated helpers are GDScript and run in every Godot 4 build, including .NET. In a C# project write your own code in C#: every Godot class is `partial`, signal delegates end in `EventHandler`, and you connect to a GDScript signal with `Connect(\"action\", Callable.From<StringName, Control>(OnAction))`. Check C# enum names against the installed Godot; do not guess them."),
    ("Do not hardcode version-sensitive values.",
     "Run `godot --version` (and `dotnet --version` in a C# project) and match `config_version`, the SDK version and the target framework to what is installed. On an existing project, keep what is there."),
    ("Commit the sidecars.",
     "Commit every `.uid` and `.import` file next to its source; ignore `.godot/`. Move or rename files inside the Godot editor, or with the editor closed and the sidecar moved with the file. A copied file is a new resource with a new UID."),
    ("Do not reuse the `ui_*` input actions for gameplay.",
     "Godot keeps them for focus and menus. Give gameplay its own actions."),
    ("Prove it in Godot, not by reading the files.",
     "After any change run the build gate below. A scene that loads without error can still have lost a node or a neighbor; the check counts them."),
]

MUST_BUILD = ["GUX-TEXT-SCALE", "GUX-SETTINGS-SAVED", "GUX-REMAP", "GUX-SUBTITLES", "GUX-JUICE-OPTIONS", "GUX-PROMPT-SWAP", "GUX-SAFE-DEVICE", "GUX-NO-FLICKER"]
ASK_A_PERSON = ["GUX-CHALLENGE-MARKED", "GUX-NO-COLOR-ALONE", "GUX-SIGNS-FEEDBACK", "GUX-REGISTER", "GUX-ONBOARD", "GUX-REFERENCE-TERMS"]


def write_scripts(script_dir, need_prompts):
    os.makedirs(script_dir, exist_ok=True)
    files = {"figma_screen.gd": SCREEN_GD, "figma_safe_area.gd": SAFE_GD}
    if need_prompts:
        files["figma_input_mode.gd"] = INPUT_MODE_GD
    out = []
    for name, text in files.items():
        p = os.path.join(script_dir, name)
        with open(p, "w") as f:
            f.write(text)
        out.append(p)
    return out


def screen_record(fx, scene_res, paths, unique):
    """One screen as plain data. `paths` maps id(design node) -> node path from the scene root."""
    g = fx["graph"]
    cs = fx["controls"]
    controls = []
    for i, c in enumerate(cs):
        aid, generated = ux.action_id(c)
        key, key_generated = ux.string_key(fx, c)
        sig = ux.SIGNALS.get(c["_cls"], ("", ""))
        neighbors = {side: {"to": cs[j]["name"], "from": src} for side, (j, src) in g["edges"][i].items()}
        tags = c["_tags"]
        controls.append({
            "name": c["name"], "type": c["_cls"], "path": paths.get(id(c), ""),
            "unique_name": ("%" + unique[id(c)]) if id(c) in unique else None,
            "action": aid, "action_generated": generated,
            "godot_signal": sig[0], "screen_signal": sig[1],
            "label": ux.text_of(c), "string_key": key if ux.text_of(c) else None,
            "string_key_generated": key_generated if ux.text_of(c) else False,
            "focus_first": g["first"] == i, "neighbors": neighbors,
            "confirm": tags.get("confirm"), "undo": tags.get("undo"), "challenge": tags.get("challenge"),
        })
    frame = fx["frame"]
    return {
        "screen": fx["name"], "scene": scene_res, "root_node": fx.get("root_node", fx["name"]),
        "platform": fx["platform"], "kind": fx["kind"], "safe_area": fx["safe"],
        "design_size": [frame["_abs"][2], frame["_abs"][3]], "text_min": fx.get("text_min"),
        "target_min": fx["profile"]["target_min"], "safe_inset": fx["profile"]["safe_inset"],
        "initial_focus": paths.get(id(cs[g["first"]]), "") if g["first"] is not None else None,
        "initial_focus_generated": g["first_generated"],
        "controls": controls,
        "strings": fx.get("strings", []),
        "prompts": [{"name": p["name"], "prompt": p["_tags"]["prompt"], "path": paths.get(id(p), ""),
                     "unique_name": ("%" + unique[id(p)]) if id(p) in unique else None} for p in fx["prompts"]],
        "registers": [{"name": n, "register": r} for n, r in fx["registers"]],
    }


def build_json(design_name, screens, findings, rules, report_items, subdir):
    return {
        "schema": "figma-to-godot-handoff/1", "design": design_name, "folder": "res://%s" % subdir,
        "rules_checked": rules["checked"], "screens": screens, "findings": findings,
        "not_imported": [{"level": l, "where": w, "what": m} for (l, w, m) in report_items],
    }


def strings_csv(screens):
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["keys", "en"])
    seen = {}
    for s in screens:
        for st in s["strings"]:
            if st["key"] in seen:
                continue
            seen[st["key"]] = st["text"]
            w.writerow([st["key"], st["text"]])
    return buf.getvalue()


def _md_table(rows, header):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for r in rows:
        out.append("| " + " | ".join(str(c).replace("|", "\\|").replace("\n", " ") for c in r) + " |")
    return out


def build_markdown(data, rules, subdir):
    by_id = rules["by_id"]
    L = ["# Handoff: %s" % data["design"], "",
         "For the coding agent (or person) who makes these screens work. The screens were drawn in Figma and converted by figma2godot. This file says what each control is for, which signal to listen to, how focus moves, and what the design could not show. `handoff.json` holds the same facts as data.",
         "", "## Read this first", ""]
    for i, (rule, why) in enumerate(IMPLEMENTER_RULES, 1):
        L.append("%d. **%s** %s" % (i, rule, why))
    L += ["", "## The build gate", "", "Run these after every change. All three must pass.", "", "```bash",
          "godot --headless --path . --import",
          "godot --headless --path . --script tests/godot_check.gd      # every scene loads; theme modes swap",
          "godot --headless --path . --script tests/godot_ux_check.gd   # focus, text size, safe area, tap targets",
          "```", "",
          "Copy the two scripts from figma-to-godot's `tests/` folder if the project does not have them. In a C# project run `dotnet build` first.", ""]

    L += ["## Screens", ""]
    for s in data["screens"]:
        L += ["### %s" % s["screen"], "",
              "- Scene: `%s` (root node `%s`, script `res://%s/scripts/figma_screen.gd`)" % (s["scene"], s["root_node"], subdir),
              "- Platform: %s. Kind: %s. Design size: %g by %g." % (s["platform"], s["kind"], s["design_size"][0], s["design_size"][1]),
              "- Safe area: %s." % {"title": "title-safe; the content sits in a container that keeps it inside the inner part of a TV picture",
                                    "device": "the device's own safe area, asked for at run time",
                                    "none": "none applied", "bleed": "full bleed"}.get(s["safe_area"], s["safe_area"])]
        if s["initial_focus"]:
            L.append("- Focus when it opens: `%s`%s." % (s["initial_focus"], " (chosen by the converter, not by the designer: review it)" if s["initial_focus_generated"] else ""))
        else:
            L.append("- Nothing on this screen takes focus.")
        L.append("")
        if s["controls"]:
            rows = []
            for c in s["controls"]:
                nb = ", ".join("%s: %s%s" % (side, v["to"], "" if v["from"] == "tag" else "*") for side, v in c["neighbors"].items()) or "none"
                extra = []
                if c["confirm"]:
                    extra.append("confirm with %s" % c["confirm"])
                if c["undo"]:
                    extra.append("can be undone")
                if c["challenge"]:
                    extra.append("part of the designed challenge")
                rows.append([c["unique_name"] or c["path"], c["type"], "`%s`%s" % (c["action"], " (generated)" if c["action_generated"] else ""),
                             "`%s`" % c["screen_signal"], c["label"] or "", c["string_key"] or "", nb, "; ".join(extra)])
            L += _md_table(rows, ["Control", "Type", "Action id", "Listen for", "Label", "String key", "Focus moves to", "Notes"])
            L += ["", "A `*` marks a focus neighbor the converter worked out from the layout. The designer did not set it; check it with a controller.", ""]
        if s["prompts"]:
            L += ["Button prompts to swap when the input device changes (register `scripts/figma_input_mode.gd` as the autoload `InputMode`):", ""]
            L += ["- `%s`: %s" % (p["unique_name"] or p["path"], p["prompt"]) for p in s["prompts"]]
            L.append("")
        if s["registers"]:
            L += ["HUD registers the designer chose: " + ", ".join("%s is %s" % (r["name"], r["register"]) for r in s["registers"]) + ".", ""]
        L += ["Example (GDScript, in your own script, not in this folder):", "", "```gdscript",
              "@onready var screen: Control = $%s" % s["root_node"], "",
              "func _ready() -> void:", "\tscreen.action.connect(_on_action)", "\tscreen.value_changed.connect(_on_value_changed)", "",
              "func _on_action(id: StringName, _source: Control) -> void:", "\tmatch id:"]
        presses = [c for c in s["controls"] if c["screen_signal"].startswith("action")]
        for c in presses[:6]:
            L.append("\t\t&\"%s\":\n\t\t\tpass  # %s" % (c["action"], c["label"] or c["name"]))
        if not presses:
            L.append("\t\t_:\n\t\t\tpass")
        L += ["", "func _on_value_changed(id: StringName, value: Variant, _source: Control) -> void:", "\tpass", "```", ""]

    L += ["## Strings", "",
          "`strings.csv` lists every visible text with a key, in Godot's CSV translation layout (`keys,en`). The scenes still hold the English text so they read correctly before translation is set up. To localise: import the CSV, then set each control's text to its key (it is in the control's `figma_key` meta).", ""]

    real = [f for f in data["findings"] if f["label"] != "note"]
    notes = [f for f in data["findings"] if f["label"] == "note"]
    L += ["## What the check found in the design", ""]
    if not real:
        L += ["Nothing.", ""]
    else:
        L += ["Each row cites a rule in `rules/game-ux.json`. A failure breaks a published standard; a concern goes against platform or expert guidance; a deviation breaks this tool's own conventions. Fix these in Figma, not in the generated files.", ""]
        L += _md_table([[f["label"], f["rule"], "`%s`" % f["where"], f["msg"]] for f in real], ["", "Rule", "Where", "What"])
        L.append("")
    if notes:
        L += ["Notes:", ""] + ["- `%s`: %s" % (f["where"], f["msg"]) for f in notes] + [""]

    L += ["## What the design cannot show: you build these", ""]
    for rid in MUST_BUILD:
        r = by_id[rid]
        L.append("- **%s** (%s). %s" % (r["title"], rid, r["detail"]))
    L += ["", "## What only a person can decide", "", "Ask; do not assume.", ""]
    for rid in ASK_A_PERSON:
        r = by_id[rid]
        L.append("- **%s** (%s). %s" % (r["title"], rid, r["detail"]))
    L += ["", "## What the import dropped or approximated", ""]
    if not data["not_imported"]:
        L.append("Nothing.")
    else:
        L += ["- %s `%s`: %s" % (x["level"], x["where"], x["what"]) for x in data["not_imported"]]
    L.append("")
    return "\n".join(L)


def write(project, subdir, data, rules):
    base = os.path.join(project, subdir)
    out = []
    for name, text in (("handoff.json", json.dumps(data, indent=2, ensure_ascii=False) + "\n"),
                       ("HANDOFF.md", build_markdown(data, rules, subdir)),
                       ("strings.csv", strings_csv(data["screens"]))):
        p = os.path.join(base, name)
        with open(p, "w") as f:
            f.write(text)
        out.append(p)
    return out
