"""The handoff: what a coding agent needs to turn generated scenes into a working game UI.

Writes, under <project>/<subdir>/:
  HANDOFF.md        read this first: every screen, every control, its action, its signal
  handoff.json      the same facts as data (tests/godot_ux_check.gd reads it)
  strings.csv       keys and source text, in Godot's CSV translation layout
  scripts/*.gd      small generated helpers the scenes use
"""
import csv
import io
import json
import os

